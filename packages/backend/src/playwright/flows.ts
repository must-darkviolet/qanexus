const PROOF_SPEC = '__flow-proof__.spec.ts';

/** Requests a journey always sends (no condition on the way): what its proof waits for. */
function certain(j: Journey) {
  return j.leadsTo.filter((t) => t.conditions.length === 0);
}

export function renderProofSpec(features: { key: string; name: string; journeys: Journey[] }[]): string {
  const imports = features.map((f) => `import { ${flowsClassName(f.name)} } from '../${SUITE_DIRS.pages}/${flowsFileName(f.key).replace(/\.ts$/, '')}';`);
  const tests = features.flatMap((f) => f.journeys.map((j) => {
    const targets = certain(j);
    const guarded = new Set(j.guards.map((g) => g.alias));
    return `test(${JSON.stringify(`flow: ${f.key}.${j.name}`)}, async ({ page, qa }) => {
${targets.filter((t) => !guarded.has(t.alias)).map((t) => `  qa.observe(${JSON.stringify(t.alias)}, ${JSON.stringify(t.method)}, ${JSON.stringify(t.path)});`).join('\n')}
  await new ${flowsClassName(f.name)}(page, qa).${j.name}();
${targets.map((t) => `  await qa.expectRequestMade(${JSON.stringify(t.alias)});`).join('\n')}
});`;
  }));
  return `import { test } from '../support/qa';
${imports.join('\n')}

// Generated: proves each traced journey runs on the live application. Removed after the proof.
// Each journey is proven on its own: one that fails does not stop the others.
${tests.join('\n\n')}
`;
}

/**
 * Runs every journey once against the live application and records on each
 * whether it completed and sent what it always sends. Nothing is written to
 * the backend: every data-changing request is answered by the flow.
 */
export async function proveJourneys(opts: {
  layout: SuiteLayout;
  runId: string;
  baseUrl: string;
  features: { key: string; name: string; journeys: Journey[] }[];
  storageState: string | null;
  credentials?: Record<string, string>;
  signal?: AbortSignal;
}): Promise<void> {
  const features = opts.features.filter((f) => f.journeys.length);
  if (!features.length) return;
  const file = path.join(opts.layout.testsDir, PROOF_SPEC);
  fs.writeFileSync(file, renderProofSpec(features), 'utf8');
  try {
    const run = await runSuite({
      layout: opts.layout, runId: `${opts.runId}-flows`, baseUrl: opts.baseUrl, specs: [`${SUITE_DIRS.tests}/${PROOF_SPEC}`],
      storageState: opts.storageState, authRequired: Boolean(opts.storageState), credentials: opts.credentials, signal: opts.signal, retries: 0,
    });
    for (const f of features) for (const j of f.journeys) {
      const r = run.results.find((x) => x.title.endsWith(`flow: ${f.key}.${j.name}`) || x.title === `flow: ${f.key}.${j.name}`);
      const detail = r ? (r.errorMessage ?? r.outcome).split('\n').slice(0, 2).join(' ').slice(0, 300) : run.executionError ?? 'the proof did not run';
      // The network or the environment failing says nothing about the journey: it stays "not yet proven".
      if (!r || (r.outcome !== 'passed' && /net::ERR_|ECONNREFUSED|ECONNRESET|ETIMEDOUT|ENOTFOUND|Target (page|closed)|browser has been closed/.test(detail))) {
        j.proven = undefined;
        log.warn(`Journey ${f.key}.${j.name}: not proven because the environment failed (${detail.slice(0, 120)}).`);
        continue;
      }
      j.proven = { ok: r.outcome === 'passed', detail: r.outcome === 'passed' ? 'completed' : detail };
      log.info(`Journey ${f.key}.${j.name}: ${j.proven.ok ? 'proven' : `not proven - ${j.proven.detail}`}`);
    }
  } finally {
    fs.rmSync(file, { force: true });
  }
}
