/**
 * Playwright project scaffolding (spec section 13).
 *
 * Generated tests live in their own Playwright project under the project's
 * workspace, not inside the user's repository - so nothing is ever overwritten
 * in the repo, and the suite can be regenerated safely.
 *
 * Layout:
 *   playwright.config.ts
 *   tests/     one <feature>.spec.ts per feature
 *   pages/     page objects
 *   fixtures/  JSON test data
 *   support/   the qa fixture: helpers, API stubbing, evidence capture
 *   utils/     data helpers
 */
