export interface SuiteLayout {
  root: string;
  testsDir: string;
  pagesDir: string;
  fixturesDir: string;
  supportDir: string;
  utilsDir: string;
  artifactsDir: string;
  /** Per-run output (videos, screenshots, traces) lives under here. */
  runsDir: string;
  screenshotsDir: string;
}

/** Suite-relative directory names, used in generated paths like "tests/users.spec.ts". */
export const SUITE_DIRS = { tests: 'tests', pages: 'pages', fixtures: 'fixtures', retired: 'retired' } as const;
export const SPEC_SUFFIX = '.spec.ts';

export function suiteLayout(projectId: string): SuiteLayout {
  const root = path.join(env.workspaceRoot, projectId, 'qa-suite');
  const artifactsDir = path.join(env.artifactRoot, projectId);
  return {
    root,
    testsDir: path.join(root, SUITE_DIRS.tests),
    pagesDir: path.join(root, SUITE_DIRS.pages),
    fixturesDir: path.join(root, SUITE_DIRS.fixtures),
    supportDir: path.join(root, 'support'),
    utilsDir: path.join(root, 'utils'),
    artifactsDir,
    runsDir: path.join(artifactsDir, 'runs'),
    screenshotsDir: path.join(artifactsDir, 'screenshots'),
  };
}

