/**
 * Makes "playwright" importable from the suite even when the workspace root
 * lives outside this repository's node_modules tree. The link points at the
 * same package the runner launches, so config, fixture and CLI share one copy.
 */
function linkPlaywright(root: string): void {
  const require = createRequire(import.meta.url);
  for (const name of ['playwright', 'playwright-core']) {
    let pkgDir: string;
    try { pkgDir = path.dirname(require.resolve(`${name}/package.json`)); } catch { continue; }
    const link = path.join(root, 'node_modules', name);
    try {
      if (fs.existsSync(link)) continue;
      fs.mkdirSync(path.dirname(link), { recursive: true });
      fs.symlinkSync(pkgDir, link, process.platform === 'win32' ? 'junction' : 'dir');
    } catch (e) {
      log.warn(`Could not link ${name} into the suite: ${(e as Error).message}`);
    }
  }
}

/**
 * Creates (or refreshes) the suite skeleton. Spec files and page objects are
 * written separately by codegen so regeneration never clobbers the skeleton.
 */
export function ensureSuiteScaffold(projectId: string): SuiteLayout {
  const layout = suiteLayout(projectId);

  for (const dir of [
    layout.root, layout.testsDir, layout.pagesDir, layout.fixturesDir,
    layout.supportDir, layout.utilsDir, layout.artifactsDir, layout.runsDir, layout.screenshotsDir,
  ]) {
    fs.mkdirSync(dir, { recursive: true });
  }

  writeIfChanged(path.join(layout.root, 'playwright.config.ts'), PLAYWRIGHT_CONFIG);
  writeIfChanged(path.join(layout.root, 'tsconfig.json'), TSCONFIG);
  writeIfChanged(path.join(layout.supportDir, 'qa.ts'), SUPPORT_QA);
  writeIfChanged(path.join(layout.supportDir, 'progress-reporter.ts'), PROGRESS_REPORTER);
  writeIfChanged(path.join(layout.utilsDir, 'data.ts'), UTILS_DATA);
  linkPlaywright(layout.root);

  log.debug(`Suite scaffold ready at ${layout.root}`);
  return layout;
}

function writeIfChanged(file: string, content: string): void {
  try {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
  } catch { /* fall through and write */ }
  fs.writeFileSync(file, content, 'utf8');
}

